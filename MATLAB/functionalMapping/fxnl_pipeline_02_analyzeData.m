%% Helper functions
function badChannels = getBadCh(dataStruct)
    badChannels = [];
    flnames = fieldnames(dataStruct);
    for i = 1:numel(flnames)
        badChannels = [badChannels, dataStruct.(flnames{i}).BadChannels];
    end
    badChannels = unique(badChannels);
end
