    ch_BB_avg = mean(ch_nps,1);

    figure('Position', [200 150 1300 800])
    gscatter(1:numel(tr_sc),ch_BB_avg,tr_sc)
    title(ch_names(j))
    subtitle(['HFB r^2=' num2str(rvals.r_HFB(j))  ', HFB p=' num2str(rvals.p_HFB(j)) ' // LFB r^2=' num2str(rvals.r_LFB(j))  ', LFB p=' num2str(rvals.p_LFB(j))])
    legend({'Rest';'Task'})
    ylabel(sprintf('Normalized Power, %d-%d Hz' , HFB(1),HFB(end)))
    xlabel('Trial number')
    xlim("tight")
    fontsize(16,'points')

    % Save Figures
    if SAVE_FIG
        figname = sprintf([fig_pth filesep 'ch%d_rval_dist.png'],j);
        saveas(gcf,figname);
    end
end

